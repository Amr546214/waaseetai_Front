import { build } from 'esbuild';
import { readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { resolve, join } from 'node:path';

// Shared pure TS metadata is bundled for Node; no browser/Angular code or network calls run here.
export async function loadSeo() {
  const bundled = await build({ entryPoints: ['src/app/core/seo/site-seo.ts'], bundle: true, write: false, platform: 'node', format: 'esm' });
  return import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);
}
export function renderShell(html, page, seo, canonical = true) {
  const e = seo.escapeHtml;
  const title = `${page.title} | ${seo.SITE_NAME}`;
  const setMeta = (attr, key, value) => {
    const tag = `<meta ${attr}="${key}" content="${e(value)}">`;
    const re = new RegExp(`<meta\\b(?=[^>]*\\b${attr}="${key}")[^>]*>`, 'g');
    html = re.test(html) ? html.replace(re, () => tag) : html.replace('</head>', `${tag}</head>`);
  };
  html = html.replace(/<title>[^<]*<\/title>/, () => `<title>${e(title)}</title>`);
  setMeta('name', 'description', page.description);
  // Host-specific noindex is sent as an HTTP header by nginx/Express, including before JS runs.
  setMeta('name', 'robots', seo.INDEX_ROBOTS);
  setMeta('property', 'og:title', title);
  setMeta('property', 'og:description', page.description);
  setMeta('property', 'og:url', `${seo.SITE_ORIGIN}${page.path}`);
  setMeta('name', 'twitter:title', title);
  setMeta('name', 'twitter:description', page.description);
  html = html.replace(/<link\b(?=[^>]*\brel="canonical")[^>]*>/g, '');
  if (canonical) html = html.replace('</head>', `<link rel="canonical" href="${e(seo.SITE_ORIGIN + page.path)}"></head>`);
  html = html.replace(/<script\b[^>]*data-ws-seo-schema[^>]*>[\s\S]*?<\/script>/, () => `<script type="application/ld+json" data-ws-seo-schema>${seo.schemaJson(seo.organizationSchema())}</script>`);
  return html;
}
export async function buildSeo(outDir = 'dist/frontend') {
  const seo = await loadSeo();
  const browser = join(outDir, 'browser');
  let shellPath = join(browser, 'index.csr.html');
  let shell;
  try { shell = await readFile(shellPath, 'utf8'); }
  catch { shellPath = join(browser, 'index.html'); shell = await readFile(shellPath, 'utf8'); }
  await rm(join(browser, '_seo'), { recursive: true, force: true });
  await mkdir(join(browser, '_seo'), { recursive: true });
  const files = [];
  for (const [i, page] of seo.PUBLIC_PAGES.entries()) {
    const file = `/_seo/page-${i}.html`;
    await writeFile(join(browser, file), renderShell(shell, page, seo));
    files.push(`    "${page.path}" "${file}";`);
    if (page.path !== '/') files.push(`    "${page.path}/" "${file}";`);
  }
  // The fallback is used for unknown/data-backed URLs: never point them all to the home page.
  await writeFile(shellPath, renderShell(shell, seo.PUBLIC_PAGES[0], seo, false));
  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${seo.PUBLIC_PAGES.map(p => `  <url><loc>${seo.escapeHtml(seo.SITE_ORIGIN + p.path)}</loc></url>`).join('\n')}\n</urlset>\n`;
  await writeFile(join(browser, 'sitemap.xml'), sitemap);
  const map = `# Generated by scripts/build-seo.mjs. Included at nginx http scope.\nmap $request_uri $ws_request_path {\n    ~^(?<ws_original_path>[^?]*) $ws_original_path;\n}\nmap $ws_request_path $ws_seo_file {\n    default /__ws_no_seo_file__;\n${files.join('\n')}\n}\nmap $host $ws_official_host {\n    default 0;\n    waseetai.com 1;\n    www.waseetai.com 1;\n}\nmap $ws_request_path $ws_public_path {\n    default 0;\n${seo.PUBLIC_PAGES.map(p => `    "${p.path}" 1;${p.path !== '/' ? `\n    "${p.path}/" 1;` : ''}`).join('\n')}\n    ~^/marketplace/(?:offer/)?[A-Za-z0-9_%.-]+/?$ 1;\n    ~*\\.(?:js|css|svg|ico|png|jpg|jpeg|webp|woff|woff2|ttf)$ 1;\n    /robots.txt 1;\n    /sitemap.xml 1;\n}\nmap "$ws_official_host:$ws_public_path" $ws_robots {\n    default "noindex, nofollow";\n    "1:1" "";\n}\n`;
  await writeFile(join(outDir, 'seo-map.conf'), map);
  console.log(`SEO: ${seo.PUBLIC_PAGES.length} public pages, canonical HTML shells, sitemap and nginx index policy generated.`);
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) await buildSeo(process.argv[2]);
