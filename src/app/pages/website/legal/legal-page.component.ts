import { Component, Input, HostListener, Inject, PLATFORM_ID, OnInit } from '@angular/core';
import { CommonModule, isPlatformBrowser } from '@angular/common';
import { RouterModule, ActivatedRoute } from '@angular/router';

/**
 * A content block. Plain string = paragraph, string[] = bullet list; the object forms carry the
 * design's richer markup (P-LG-002 sub-headings / checklist / callouts, P-LG-01x tables).
 * All strings are static, trusted markup written in this file.
 */
export type LegalBlock =
	| string
	| string[]
	| { h3: string }
	| { ob: string[] }
	| { callout: 'blue' | 'warn'; html: string }
	| { table: { head: string[]; rows: string[][] } };
export interface LegalSection { id: string; title: string; /** short TOC label (P-LG-002 sidebar) */ toc?: string; paragraphs: LegalBlock[]; }
export interface LegalDoc { title: string; subtitle: string; sections: LegalSection[]; }

/** Uniform view of a block for the template. */
export interface NormBlock {
	kind: 'p' | 'ul' | 'h3' | 'ob' | 'callout' | 'table';
	html?: string;
	items?: string[];
	tone?: 'blue' | 'warn';
	head?: string[];
	rows?: string[][];
}

@Component({
	selector: 'app-legal-page',
	standalone: true,
	imports: [CommonModule, RouterModule],
	templateUrl: './legal-page.component.html',
	styleUrls: ['./legal-page.component.css']
})
export class LegalPageComponent implements OnInit {
	@Input() doc!: 'lg-002' | 'lg-010' | 'lg-011' | 'lg-012' | 'lg-013' | 'lg-014';
	activeSection = 's1';

	constructor(@Inject(PLATFORM_ID) private platformId: Object, private route: ActivatedRoute) {}

	ngOnInit() {
		if (!this.doc) {
			const data = this.route.snapshot.data;
			if (data && data['doc']) this.doc = data['doc'];
		}
	}

	/** "الوثائق القانونية" side links, per design P-LG-010..014 (P-LG-001 "سياسة الاسترداد" -> /legal policy hub). */
	get related(): { label: string; route: string }[] {
		const L = {
			terms: { label: 'الشروط والأحكام', route: '/terms' },
			privacy: { label: 'سياسة الخصوصية', route: '/privacy' },
			refund: { label: 'سياسة الاسترداد', route: '/legal' },
			provider: { label: 'اتفاقية المقدم', route: '/legal/provider-agreement' },
			payment: { label: 'الدفع والنزاعات', route: '/legal/payment-escrow-disputes' },
			users: { label: 'المستخدمون والعقود', route: '/legal/users-services-contracts' },
			broker: { label: 'الوسيط والعمولات', route: '/legal/marketing-broker-commissions' },
			accred: { label: 'الاعتماد وحوكمة AI', route: '/legal/accreditation-ai-governance' },
			usage: { label: 'الاستخدام والملكية', route: '/legal/acceptable-use-ip' },
			ip: { label: 'الملكية الفكرية', route: '/legal/acceptable-use-ip' },
			report: { label: 'تقديم بلاغ', route: '/support/report-problem' }
		};
		switch (this.doc) {
			case 'lg-002': return [L.terms, L.privacy, L.refund];
			case 'lg-010': return [L.terms, L.refund, L.provider, L.users, L.broker];
			case 'lg-011': return [L.terms, L.refund, L.provider, L.payment, L.ip];
			case 'lg-012': return [L.terms, L.payment, L.accred];
			case 'lg-013': return [L.terms, L.payment, L.users, L.usage];
			case 'lg-014': return [L.terms, L.refund, L.users, L.accred, L.report];
			default: return [L.terms, L.privacy];
		}
	}

	/** P-LG-002 (provider agreement) has its own design layout; P-LG-010..014 share the annex layout. */
	get isAgreement(): boolean {
		return this.doc === 'lg-002';
	}

	norm(b: LegalBlock): NormBlock {
		if (typeof b === 'string') return { kind: 'p', html: b };
		if (Array.isArray(b)) return { kind: 'ul', items: b };
		if ('h3' in b) return { kind: 'h3', html: b.h3 };
		if ('ob' in b) return { kind: 'ob', items: b.ob };
		if ('callout' in b) return { kind: 'callout', tone: b.callout, html: b.html };
		return { kind: 'table', head: b.table.head, rows: b.table.rows };
	}

	get document(): LegalDoc {
		switch (this.doc) {
			case 'lg-002': return LG_002;
			case 'lg-010': return LG_010;
			case 'lg-011': return LG_011;
			case 'lg-012': return LG_012;
			case 'lg-013': return LG_013;
			case 'lg-014': return LG_014;
			default: return LG_011;
		}
	}

	@HostListener('window:scroll')
	onScroll() {
		if (isPlatformBrowser(this.platformId)) {
			// Design: the active TOC entry is the last section whose heading passed the header.
			let active = this.document.sections[0]?.id ?? 's1';
			for (const sec of this.document.sections) {
				const el = document.getElementById(sec.id);
				if (el && el.getBoundingClientRect().top < 120) active = sec.id;
			}
			this.activeSection = active;
		}
	}

	scrollTo(sectionId: string) {
		if (isPlatformBrowser(this.platformId)) {
			const element = document.getElementById(sectionId);
			if (element) {
				const y = element.getBoundingClientRect().top + window.pageYOffset - 90;
				window.scrollTo({ top: y, behavior: 'smooth' });
				this.activeSection = sectionId;
			}
		}
	}
}

