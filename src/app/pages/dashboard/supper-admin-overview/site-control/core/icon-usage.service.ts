import { HttpClient } from '@angular/common/http';
import { Injectable, inject, signal } from '@angular/core';
import { catchError, firstValueFrom, of } from 'rxjs';

/**
 * The four classes of the icon inventory (Round 9):
 *  - BOUND: a place follows this key (used + bound);
 *  - USED_UNBOUND: a place draws this glyph with NO key at all (must stay empty: every such place gets a key or is listed in `unboundPlaces` with its exact reason);
 *  - UNUSED: nothing draws THIS id. It is kept (never deleted) in its own collapsed section; when the same drawing is drawn elsewhere under other keys they are named in `sameDrawing`;
 *  - slot without a drawing: never offered as a card (see icon-usage.guard.spec.ts).
 */
export type IconUsageStatus = 'BOUND' | 'USED_UNBOUND' | 'UNUSED';
export interface IconUsage { status: IconUsageStatus; refs: number; unboundPlaces?: number; sameDrawing?: { places: number; keys: string[] } }
/** a place that draws an icon but cannot follow a key (never shown as editable) and WHY */
export interface UnboundPlace { file: string; line: number; reason: string; why: string }

/** generated by tools/icon-usage-report.cjs (guarded by icon-usage.guard.spec.ts) */
@Injectable({ providedIn: 'root' })
export class IconUsageService {
	private readonly http = inject(HttpClient);
	readonly phase = signal<'idle' | 'ready' | 'error'>('idle');
	readonly icons = signal<Record<string, IconUsage>>({});
	readonly unboundPlaces = signal<UnboundPlace[]>([]);
	private inflight: Promise<void> | null = null;

	load(): Promise<void> {
		if (this.inflight) return this.inflight;
		if (this.phase() === 'ready') return Promise.resolve();
		this.inflight = (async () => {
			const d = await firstValueFrom(this.http.get<{ icons: Record<string, IconUsage>; libraryOnly: Record<string, IconUsage>; unboundPlaces?: UnboundPlace[] }>('/assets/site-control/icon-usage.json').pipe(catchError(() => of(null))));
			if (!d?.icons) { this.phase.set('error'); return; }
			this.icons.set({ ...d.libraryOnly, ...d.icons }); this.unboundPlaces.set(Array.isArray(d.unboundPlaces) ? d.unboundPlaces : []); this.phase.set('ready');
		})().finally(() => { this.inflight = null; });
		return this.inflight;
	}
	get(id: string): IconUsage | null { return this.icons()[id] ?? null; }
	/** the sentence an unused card shows (null when the key is bound or unknown) */
	reason(id: string): string | null {
		const u = this.get(id); if (!u || u.status === 'BOUND') return null;
		if (u.status === 'USED_UNBOUND') return `مستعملة في الموقع (${u.unboundPlaces ?? 0} موضعًا) لكن لا موضع يتبع هذا المفتاح تحديدًا.`;
		const s = u.sameDrawing;
		return s ? `لا يرسم أي مكوّن هذا المعرّف بذاته، لكن الرسم نفسه يُرسم في ${s.places} موضعًا يتبع ${s.keys.length > 1 ? 'المفاتيح' : 'المفتاح'} ${s.keys.join('، ')}: عدّله من هناك. محفوظ ولا يُحذف.`
			: 'لا يرسمه أي مكوّن في الموقع حاليًا. محفوظ ولا يُحذف.';
	}
	/** the places that cannot follow a key, grouped by reason (collapsed list on the page) */
	groupedUnbound(): Array<{ reason: string; label: string; items: UnboundPlace[] }> {
		const LABELS: Record<string, string> = { DYNAMIC: 'رسم يُختار وقت التشغيل من بيانات أو حالة', AI_MARK: 'علامة الذكاء الاصطناعي الرسمية (تُدار من «الهوية»)', NOT_AN_ICON: 'علامة تجارية بألوانها أو رسم توضيحي (ليس أيقونة وظيفية)', NOTHING_DRAWN: 'لا يُرسم شيء افتراضيًا (المُعقّم يحذف عناصرها)', CONTENT_DRIVEN: 'أيقونة من بيانات المحتوى' };
		const m = new Map<string, UnboundPlace[]>(); for (const p of this.unboundPlaces()) (m.get(p.reason) || m.set(p.reason, []).get(p.reason)!).push(p);
		return [...m.entries()].map(([reason, items]) => ({ reason, label: LABELS[reason] ?? reason, items })).sort((a, b) => b.items.length - a.items.length);
	}
}
